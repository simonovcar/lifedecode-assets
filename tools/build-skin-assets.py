"""Build Website V2 full-character skin images from the real skin PNGs.

The new skin system (one complete character sprite per skin, no hat/body
overlays) lives in the owner's local development build. Names, rarity,
waves and PNG mappings come from tools/skin-catalog.json, the verified
development catalog. The owner supplied the original PNGs (1024x1536
RGBA) as uploads; this tool turns them into web assets. It never invents
or substitutes artwork: a skin without its catalog PNG is simply not built.

    python3 tools/build-skin-assets.py <folder-with-skin-pngs>

Outputs, per skin (slug = catalog id with "_" -> "-"):
  assets/v2/skins/<slug>-1200.webp   large preview (trimmed, 1200px tall)
  assets/v2/skins/<slug>-600.webp    preview for phones / 1x screens
  assets/v2/skins/<slug>-thumb.webp  240px-tall thumbnail
  assets/v2/skins/manifest.json      source file, catalog data, sizes
  tools/generated/skin-roster.js     roster spliced into ludo78.js by
                                     tools/build-website-v2.mjs

Starter forms (Base Blue / Base Rose) are built only from their real
assets, spirit_base_blue.png and spirit_base_rose.png. Until those files
are supplied the starters are left out of the gallery; the older
adultblue3.png / adultpink3.png sprites are never used in their place.
Prices are in the catalog but are not shown on the marketing site.
"""
import json
import os
import sys

from PIL import Image

if len(sys.argv) < 2:
    sys.exit(__doc__)
SRC = os.path.abspath(sys.argv[1])
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "assets", "v2", "skins")
GEN = os.path.join(ROOT, "tools", "generated")
os.makedirs(OUT, exist_ok=True)
os.makedirs(GEN, exist_ok=True)

CATALOG = json.load(open(os.path.join(ROOT, "tools", "skin-catalog.json")))
SKINS = {k["asset"]: k for k in CATALOG["skins"]}
STARTERS = {k["asset"]: k for k in CATALOG["starters"]}


def glow_colour(im):
    # Average colour of the most saturated opaque pixels: a backdrop tint
    # sampled from the artwork itself, not picked by hand.
    small = im.copy()
    small.thumbnail((96, 96))
    px = []
    for r, g, b, a in (small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata()):
        if a < 200:
            continue
        mx, mn = max(r, g, b), min(r, g, b)
        if mx < 60:
            continue
        px.append((mx - mn, r, g, b))
    if not px:
        return "#8a6bff"
    px.sort(reverse=True)
    top = px[: max(12, len(px) // 6)]
    r = sum(p[1] for p in top) // len(top)
    g = sum(p[2] for p in top) // len(top)
    b = sum(p[3] for p in top) // len(top)
    return "#%02x%02x%02x" % (r, g, b)


present = set(os.listdir(SRC))
missing = sorted(f for f in list(SKINS) + list(STARTERS) if f not in present)
roster, manifest = [], {}
for f in [k["asset"] for k in CATALOG["starters"]] + [k["asset"] for k in CATALOG["skins"]]:
    if f not in present:
        continue
    k = STARTERS.get(f) or SKINS[f]
    starter = f in STARTERS
    slug = ("base-" + k["id"].split("_")[-1]) if starter else k["id"].replace("_", "-")
    im = Image.open(os.path.join(SRC, f)).convert("RGBA")
    bbox = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    if bbox:
        im = im.crop(bbox)
    entry = {}
    for suffix, h, q in (("1200", 1200, 86), ("600", 600, 84), ("thumb", 240, 80)):
        h = min(h, im.height)
        w = round(im.width * h / im.height)
        name = f"{slug}-{suffix}.webp"
        im.resize((w, h), Image.LANCZOS).save(os.path.join(OUT, name), "WEBP", quality=q, method=6, alpha_quality=92)
        entry[suffix] = {"file": name, "size": [w, h], "bytes": os.path.getsize(os.path.join(OUT, name))}
    colour = glow_colour(im)
    manifest[slug] = {"sourceFile": f, "catalogId": k["id"], "name": k["name"], "starter": starter,
                      "rarity": k.get("rarity"), "wave": k.get("wave"), "glow": colour, "images": entry}
    roster.append({"id": slug, "name": k["name"], "starter": starter,
                   "rarity": k.get("rarity"), "wave": k.get("wave"),
                   "glow": colour, "w": entry["1200"]["size"][0], "h": entry["1200"]["size"][1],
                   "tw": entry["thumb"]["size"][0], "th": entry["thumb"]["size"][1]})

with open(os.path.join(OUT, "manifest.json"), "w") as fh:
    json.dump({"source": "owner upload (LifeDecode-Skins-Part1..6.zip), local development build",
               "catalog": "tools/skin-catalog.json (verified development catalog)",
               "missingAssets": missing,
               "legacy": "legacy/ holds the older adultblue3/adultpink3 sprites; they are not the Base Blue/Base Rose starters and are not used",
               "skins": manifest}, fh, indent=2)

with open(os.path.join(GEN, "skin-roster.js"), "w") as fh:
    fh.write("  // GENERATED by tools/build-skin-assets.py from tools/skin-catalog.json - do not edit by hand.\n")
    fh.write("  // Catalog order; starters first, and only when their real artwork was supplied.\n")
    fh.write("  const SKIN_ROSTER = " + json.dumps(roster, ensure_ascii=False, indent=2).replace("\n", "\n  ") + ";\n")

total = sum(e["bytes"] for m in manifest.values() for e in m["images"].values())
print(f"{len(roster)} skins built ({sum(s['starter'] for s in roster)} starters), {total / 1024 / 1024:.1f} MB total; "
      f"missing assets: {', '.join(missing) or 'none'}")
